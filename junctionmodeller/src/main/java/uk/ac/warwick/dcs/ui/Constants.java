package uk.ac.warwick.dcs.ui;

/**
 * Static container for constant used in the UI.
 */
public abstract class Constants {
    /**
     * Width of main window in pixels.
     */
    public static final int WINDOW_WIDTH = 668;

    /**
     * Height of main window in pixels.
     */
    public static final int WINDOW_HEIGHT = 768;

    /**
     * Maximum number of incoming (or outgoing) lanes.
     */
    public static final int MAX_LANES = 5;

    /**
     * List of user-friendly names to be used by UI elements.
     */
    public static final String[] DIRECTIONS = { "North", "East", "South", "West" };
}
